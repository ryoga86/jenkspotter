#!/usr/bin/env python3
"""Creates docker/.env with random credentials for the local test Jenkins.

The file is git-ignored and only readable by you. Run it once before `docker compose up`;
it refuses to overwrite an existing .env (delete it and run `docker compose down -v` to rotate).

Afterwards, to run the integration tests against the container:

    set -a; . docker/.env; set +a
    ./gradlew test
"""
import secrets
import sys
from pathlib import Path

ENV = Path(__file__).resolve().parent / ".env"

if ENV.exists():
    sys.exit(f"{ENV} already exists - delete it (and run `docker compose down -v`) to generate new credentials")

lines = [
    "# Generated by docker/setup_env.py - local test instance only, never commit.",
    "JENKSPOTTER_IT_URL=http://localhost:18080",
    # Jenkins API tokens are '11' followed by 32 hex characters.
    f"JENKINS_TEST_TOKEN=11{secrets.token_hex(16)}",
    f"JENKINS_DEV_PASSWORD={secrets.token_urlsafe(18)}",
    f"JENKINS_OTHER_PASSWORD={secrets.token_urlsafe(18)}",
    f"JENKINS_DEPLOY_SECRET={secrets.token_urlsafe(18)}",
]
ENV.write_text("\n".join(lines) + "\n")
ENV.chmod(0o600)
print(f"Wrote {ENV} (mode 600)")
